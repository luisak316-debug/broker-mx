function normalizeUsE164(raw: string): string | null {
  const digits = raw.replace(/\D/g, '');
  const national = digits.startsWith('1') ? digits.slice(1) : digits;
  if (national.length !== 10) return null;
  return `+1${national}`;
}

export const US_EMITTER_POOL: string[] = [
  ...new Set(
    RAW_US_EMITTERS.map(normalizeUsE164).filter((n): n is string => n !== null),
  ),
];

export function pickRandomUsEmitter(): string {
  if (US_EMITTER_POOL.length === 0) {
    throw new Error('Pool de números US vacío.');
  }
  const i = Math.floor(Math.random() * US_EMITTER_POOL.length);
  return US_EMITTER_POOL[i]!;
}

export function maskUsEmitter(e164: string): string {
  const d = e164.replace(/\D/g, '');
  return d.length >= 4 ? `+1 ******${d.slice(-4)}` : '+1 ****';
}
